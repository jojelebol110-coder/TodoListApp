    private void jButtonSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSaveActionPerformed
        String name = jTextFieldName.getText();
        String product = jTextFieldProduct.getText();
        String price = jTextFieldPrice.getText();
        String status = jTextFieldStatus.getText();
        boolean success;
        if (selectedId == null) {
            success = controller.handleAddTask(name, product, price, status);
        } else {
            success = controller.handleUpdateTask(selectedId, name, product, price, status);
        }
        if (!success) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please complete all fields and select a valid record.",
                    "Invalid input", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        clearFields();
    }//GEN-LAST:event_jButtonSaveActionPerformed

    public void refreshTaskList() {
        if (controller != null) tableModel.setTasks(controller.getAllTask());
    }

    private void loadSelectedRecord() {
        int row = jTableListOfTask.getSelectedRow();
        if (row < 0) return;
        int modelRow = jTableListOfTask.convertRowIndexToModel(row);
        selectedId = tableModel.getTaskId(modelRow);
        model.Task task = controller.getTaskDetails(selectedId);
        if (task != null) {
            jTextFieldName.setText(task.getName());
            jTextFieldProduct.setText(task.getProduct());
            jTextFieldPrice.setText(task.getPrice());
            jTextFieldStatus.setText(task.getStatus());
            jButtonSave.setText("Update");
        }
    }

    private void deleteSelectedRecord() {
        if (selectedId == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a record to delete.");
            return;
        }
        int choice = javax.swing.JOptionPane.showConfirmDialog(this,
                "Delete the selected record?", "Confirm delete", javax.swing.JOptionPane.YES_NO_OPTION);
        if (choice == javax.swing.JOptionPane.YES_OPTION) {
            if (controller.handleDeleteTask(selectedId)) clearFields();
        }
    }

    private void clearFields() {
        selectedId = null;
        jTextFieldName.setText("");
        jTextFieldProduct.setText("");
        jTextFieldPrice.setText("");
        jTextFieldStatus.setText("");
        jTableListOfTask.clearSelection();
        jButtonSave.setText("Save");
    }

